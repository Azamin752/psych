function inyo_step(){
  let size = 255
  
  let g = createGraphics(size,size);
  g.beginClip();
  g.circle(size/2,size/2,size);
  g.endClip();
  
  for(let i=0;i<=size;i++){
    if(i<size/2){
    g.stroke(0)
    }else{
    g.stroke(255)
    }
    g.line(0,i,size,i)
  }
  return g
}


function inyo_shade(){
  let size = 255
  
  let g = createGraphics(size,size);
  g.beginClip();
  g.circle(size/2,size/2,size);
  g.endClip();
  
  for(let i=0;i<=size;i++){
    g.stroke(i)
    g.line(0,i,size,i)
  }
  return g
}

function plot(img,x,y,size_x,size_y,n){

    if(n==0){
    angle = 0
  }else if(n==1){
    angle = PI
  }
  
  push();
  translate(x, y);
  rotate(angle);
  imageMode(CENTER);
  image(img, 0, 0, size_x, size_y);
  pop();
}
